using System.Security.Cryptography;
using System.Security.Cryptography.X509Certificates;
using Npgsql;

namespace NexoRuta.IntegrationTests.Fixtures;

/// <summary>Creates an isolated key ring and certificate for production-host integration tests.</summary>
public sealed class SharedDataProtectionTestStore : IAsyncDisposable
{
    private readonly DirectoryInfo certificateDirectory;

    private SharedDataProtectionTestStore(string connectionString, string certificatePath,
        DirectoryInfo certificateDirectory)
    {
        ConnectionString = connectionString;
        CertificatePath = certificatePath;
        this.certificateDirectory = certificateDirectory;
    }

    public string ConnectionString { get; }
    public string CertificatePath { get; }

    public void Configure(IDictionary<string, string?> settings)
    {
        settings["ConnectionStrings:DataProtection"] = ConnectionString;
        settings["DataProtection:CertificatePath"] = CertificatePath;
    }

    public static async Task<SharedDataProtectionTestStore> CreateAsync(IntegrationDatabase database,
        string ring = "api")
    {
        if (ring is not ("api" or "admin" or "backoffice" or "commerce" or "tracking"))
            throw new ArgumentOutOfRangeException(nameof(ring));

        var directory = Directory.CreateTempSubdirectory("nexoruta-shared-keys-");
        try
        {
            var certificatePath = WriteCertificate(directory.FullName);
            var role = $"keys_test_{Guid.NewGuid():N}";
            var password = Convert.ToHexString(RandomNumberGenerator.GetBytes(24));
            var schema = $"nexoruta_keys_{ring}";
            await using var sql = new NpgsqlConnection(database.ConnectionString);
            await sql.OpenAsync();
            await using var setup = new NpgsqlCommand($$"""
                CREATE ROLE "{{role}}" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS PASSWORD '{{password}}';
                CREATE SCHEMA "{{schema}}" AUTHORIZATION "{{role}}";
                REVOKE ALL ON SCHEMA "{{schema}}" FROM PUBLIC;
                CREATE TABLE "{{schema}}"."DataProtectionKeys" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "FriendlyName" text NULL, "Xml" text NULL);
                ALTER TABLE "{{schema}}"."DataProtectionKeys" OWNER TO "{{role}}";
                """, sql);
            await setup.ExecuteNonQueryAsync();
            var connectionString = new NpgsqlConnectionStringBuilder(database.ConnectionString)
            {
                Username = role,
                Password = password,
                Pooling = false
            }.ConnectionString;
            return new(connectionString, certificatePath, directory);
        }
        catch
        {
            directory.Delete(recursive: true);
            throw;
        }
    }

    public ValueTask DisposeAsync()
    {
        certificateDirectory.Delete(recursive: true);
        return ValueTask.CompletedTask;
    }

    private static string WriteCertificate(string directory)
    {
        using var rsa = RSA.Create(2048);
        var request = new CertificateRequest("CN=NexoRuta integration key ring", rsa,
            HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
        using var certificate = request.CreateSelfSigned(DateTimeOffset.UtcNow.AddMinutes(-1),
            DateTimeOffset.UtcNow.AddDays(1));
        var path = Path.Combine(directory, "keys.pfx");
        File.WriteAllBytes(path, certificate.Export(X509ContentType.Pfx));
        return path;
    }
}
